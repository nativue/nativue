// Writes src/lucide.ts: one component per Lucide icon, named <Icon>Icon (CameraIcon), so they never
// clash with native components (Lucide has Image, Text, Link...). Run after upgrading lucide.
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const lucidePackagePath = require.resolve('lucide/package.json')
const { version } = JSON.parse(readFileSync(lucidePackagePath, 'utf8'))
const entry = readFileSync(lucidePackagePath.replace('package.json', 'dist/esm/lucide.mjs'), 'utf8')

// Each icon file is exported once per name (current and deprecated aliases): keep the name that
// matches the file, e.g. './icons/file-video-camera.mjs' -> FileVideoCamera.
function pascalCase(fileName) {
  return fileName.replace(/(^|-)([a-z0-9])/g, (_, _dash, character) => character.toUpperCase())
}

const iconNames = [...entry.matchAll(/from '\.\/icons\/([a-z0-9-]+)\.mjs'/g)]
  .map(([, fileName]) => pascalCase(fileName))
  .filter((name, index, names) => names.indexOf(name) === index)
  .sort()

const lines = [
  `// Generated by scripts/generate-lucide.mjs from lucide@${version}: do not edit.`,
  "import * as lucide from 'lucide'",
  "import { createIcon } from './create-icon'",
  '',
  ...iconNames.map(
    (name) => `export const ${name}Icon = /* @__PURE__ */ createIcon('${name}', lucide.${name})`,
  ),
  '',
]

writeFileSync(new URL('../src/lucide.ts', import.meta.url), lines.join('\n'))
console.log(`src/lucide.ts: ${iconNames.length} icons from lucide@${version}`)
